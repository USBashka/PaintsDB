window.qaResult=null;
(async()=>{
  const checks=[];
  const wait=ms=>new Promise(resolve=>setTimeout(resolve,ms));
  const until=async predicate=>{for(let n=0;n<100;n++){if(predicate())return;await wait(50);}throw new Error('Ожидание интерфейса истекло');};
  const assert=(value,message)=>{if(!value)throw new Error(message);checks.push(message);};
  const enter=(selector,value)=>{const input=document.querySelector(selector);input.value=value;input.dispatchEvent(new Event('input',{bubbles:true}));};
  const click=selector=>document.querySelector(selector).click();
  const shot=async name=>{await wait(200);await window.pywebview.api.checkpoint(name);};
  try{
    assert(document.querySelectorAll('[data-recipe]').length===3,'Демонстрационные рецепты загружены');
    await shot('recipes');
    click('[data-view="components"]');await until(()=>document.querySelector('#add-component'));
    assert(document.querySelectorAll('[data-component]').length===3,'Справочник компонентов загружен');
    await shot('components');
    click('[data-component="2"]');await until(()=>document.querySelector('#save-component'));
    document.querySelector('details').open=true;await shot('component-prices');
    click('[data-close]');
    click('[data-view="recipes"]');await until(()=>document.querySelector('#add-recipe'));
    click('#add-recipe');await until(()=>document.querySelector('#save-recipe'));
    enter('.component-search','белый');await until(()=>document.querySelector('[data-candidate]'));
    document.querySelector('[data-candidate]').dispatchEvent(new MouseEvent('mousedown',{bubbles:true}));
    enter('.mass-expression','20+15+кап');await until(()=>document.querySelector('#total-mass').textContent==='36.000');
    assert(document.querySelector('#total-cost').textContent==='39.600','Выражение массы пересчитано в интерфейсе');
    await shot('recipe-new');
    click('#save-recipe');await until(()=>document.querySelector('#duplicate'));
    assert(document.querySelector('#r-name').value===''&&document.querySelector('#r-color_code').value==='','Рецепт сохранён без описательных полей');
    click('#back');await until(()=>document.querySelector('#add-recipe'));
    assert(document.querySelectorAll('[data-recipe]').length===4,'Сохранение обновило список');
    click('[data-recipe="1"]');await until(()=>document.querySelector('#history'));
    assert(document.querySelectorAll('#chart circle').length>0,'График рецепта построен');
    await shot('recipe');
    click('#back');await until(()=>document.querySelector('[data-select="1"]'));
    click('[data-select="1"]');click('[data-select="2"]');click('#compare-selected');await until(()=>document.querySelectorAll('.variant').length===2);
    await until(()=>document.querySelectorAll('#chart circle').length>0);
    assert(document.querySelector('.variant').textContent.includes('1710.000'),'Сравнение использует выбранный месяц и 1 кг');
    await shot('compare');
    click('[data-view="components"]');await until(()=>document.querySelector('#import'));
    click('#import');await until(()=>document.querySelectorAll('[data-import-row]').length===5);
    assert(document.querySelectorAll('[data-import-row]:checked').length===2,'Импорт явно выделяет проверенные строки');
    assert(document.querySelectorAll('[data-import-row]:disabled').length===1,'Ошибка Excel блокирует строку');
    await shot('import');click('#apply-import');await until(()=>!document.querySelector('#dialog').open);
    await until(()=>document.querySelectorAll('[data-component]').length===4);
    assert(document.querySelector('#notice').textContent.includes('без прайса 1'),'Импорт не подменяет отсутствующую цену нулём');
    click('[data-view="recipes"]');await until(()=>document.querySelector('[data-recipe="1"]'));click('[data-recipe="1"]');await until(()=>document.querySelector('#save-recipe'));
    enter('#r-name','Несохранённая правка');
    await window.pywebview.api.simulate_mcp_edit(1);
    await until(()=>document.querySelector('#notice').textContent.includes('MCP'));
    assert(document.querySelector('#r-name').value==='Несохранённая правка','Уведомление MCP сохраняет несохранённый ввод');
    click('#save-recipe');await until(()=>document.querySelector('#editor-error').textContent.includes('изменена'));
    assert(document.querySelector('#r-name').value==='Несохранённая правка','Конфликт не затирает данные другой записи');
    await shot('mcp-conflict');
    window.qaResult={ok:true,checks,errors:window.uiErrors};
  }catch(e){window.qaResult={ok:false,checks,error:String(e.stack||e),errors:window.uiErrors};}
})();
